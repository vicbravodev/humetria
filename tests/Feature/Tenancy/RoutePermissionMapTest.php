it('answers 404 to whoever lacks the permission of exactly the routes that must not be known to exist', function (): void {
    $hidden = array_values(array_filter(
        array_map(fn (LaravelRoute $route): string => (string) $route->getName(), array_filter(
            Route::getRoutes()->getRoutes(),
            fn (LaravelRoute $route): bool => in_array(RequireRoutePermission::class, $route->gatherMiddleware(), true),
        )),
        fn (string $name): bool => RoutePermissions::refusalStatus($name) === 404,
    ));

    sort($hidden);

    expect($hidden)->toBe([
        'tenant.campaigns.screenings',
        'tenant.campaigns.screenings.update',
        'tenant.telework.checklist.draft',
        'tenant.telework.checklist.publish',
        'tenant.telework.checklist.questions.destroy',
        'tenant.telework.checklist.questions.move',
        'tenant.telework.checklist.questions.store',
        'tenant.telework.checklist.questions.update',
        'tenant.telework.evidence.store',
